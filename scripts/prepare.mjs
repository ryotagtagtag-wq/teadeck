import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { requireToolchain } from './toolchain.mjs';
import { preparationFingerprint } from './build_state.mjs';

const root = path.resolve(import.meta.dirname, '..');
const lock = JSON.parse(await readFile(path.join(root, 'upstream.lock.json'), 'utf8'));
const work = path.join(root, '.work');
const upstream = path.join(work, 'upstream');
const marker = path.join(work, 'teadeck-owned');
// Check before replacing a prepared checkout, not after losing its dependencies.
requireToolchain();
const args = process.argv.slice(2);
if (args.length && (args.length !== 2 || args[0] !== '--source')) {
  throw new Error('Usage: node scripts/prepare.mjs [--source /path/to/git/repository]');
}
function git(args, cwd = root) {
  const result = spawnSync('git', args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`git ${args[0]} failed`);
}
await mkdir(work, { recursive: true });
try {
  await readFile(marker);
} catch {
  const entries = await readdir(work);
  if (entries.length) throw new Error('Refusing to replace an unowned .work directory');
  await writeFile(marker, 'Generated by scripts/prepare.mjs\n');
}
await rm(upstream, { recursive: true, force: true });
await rm(path.join(work, 'prepared.sha256'), { force: true });
// Fetch only the pinned commit; dirty/untracked source files and remote history
// never enter the build context.
await mkdir(upstream);
git(['init', '--quiet'], upstream);
git(['remote', 'add', 'origin', args[1] ? path.resolve(args[1]) : lock.repository], upstream);
git(['fetch', '--depth=1', 'origin', lock.commit], upstream);
git(['checkout', '--detach', 'FETCH_HEAD'], upstream);
const actual = spawnSync('git', ['rev-parse', 'HEAD'], { cwd: upstream, encoding: 'utf8' });
if (actual.status !== 0 || actual.stdout.trim() !== lock.commit) throw new Error('Upstream commit mismatch');
const pkg = JSON.parse(await readFile(path.join(upstream, 'package.json'), 'utf8'));
if (pkg.packageManager !== lock.packageManager) throw new Error('Upstream package manager mismatch');
const patches = await readdir(path.join(root, 'patches')).catch(error => {
  if (error.code === 'ENOENT') return [];
  throw error;
});
for (const patch of patches.filter(name => name.endsWith('.patch')).sort()) {
  git(['apply', '--check', path.join(root, 'patches', patch)], upstream);
  git(['apply', path.join(root, 'patches', patch)], upstream);
}
await cp(path.join(root, 'integration'), path.join(upstream, 'app/javascript/teadeck'), {
  recursive: true,
  filter: source => path.basename(source) !== 'vite.config.mts',
});
await cp(path.join(root, 'integration/vite.config.mts'), path.join(upstream, 'teadeck.vite.config.mts'));
await writeFile(path.join(work, 'prepared.sha256'), await preparationFingerprint(root));
console.log(`Prepared Mastodon ${lock.commit} in ${upstream}`);
